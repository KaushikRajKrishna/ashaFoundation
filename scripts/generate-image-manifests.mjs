// Auto-run before `next dev` / `next build` (see package.json "predev"/"prebuild").
// Scans each folder below and (re)writes a manifest.ts with a static `import`
// per image plus an exported array — so dropping a new file into the folder
// is enough to make it show up, with no component code changes.
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const IMAGE_EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".svg"]);

const rootDir = path.dirname(fileURLToPath(import.meta.url));
const foldersToScan = [
  path.join(rootDir, "..", "src", "assets", "images", "carousel"),
  path.join(rootDir, "..", "src", "assets", "images", "gallery"),
];

function toIdentifier(fileName, index) {
  const base = path
    .parse(fileName)
    .name.replace(/[^a-zA-Z0-9]+/g, "_")
    .replace(/^[0-9]/, "_$&");
  return `img_${index}_${base}`;
}

for (const folder of foldersToScan) {
  let entries;
  try {
    entries = readdirSync(folder, { withFileTypes: true });
  } catch {
    console.warn(`[generate-image-manifests] Skipping missing folder: ${folder}`);
    continue;
  }

  const files = entries
    .filter((entry) => entry.isFile() && IMAGE_EXTENSIONS.has(path.extname(entry.name).toLowerCase()))
    .map((entry) => entry.name)
    .filter((name) => name !== "manifest.ts")
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

  const imports = files
    .map((file, i) => `import ${toIdentifier(file, i)} from "./${file}";`)
    .join("\n");

  const arrayEntries = files
    .map((file, i) => `  { image: ${toIdentifier(file, i)}, fileName: ${JSON.stringify(file)} },`)
    .join("\n");

  const manifestSource = `// AUTO-GENERATED by scripts/generate-image-manifests.mjs — do not edit by hand.
// Regenerated automatically on \`next dev\` / \`next build\`. Add or remove image
// files in this folder and re-run dev/build to update this file.
import type { StaticImageData } from "next/image";

export interface ManifestEntry {
  image: StaticImageData;
  fileName: string;
}

${imports}

export const images: ManifestEntry[] = [
${arrayEntries}
];
`;

  writeFileSync(path.join(folder, "manifest.ts"), manifestSource, "utf8");
  console.log(`[generate-image-manifests] Wrote ${files.length} image(s) -> ${path.join(folder, "manifest.ts")}`);
}
