// Auto-run before `next dev` / `next build` (see package.json "predev"/"prebuild").
// Scans src/content/blogs/<slug>/ folders — each holding exactly one .json file
// and one image file — and (re)writes manifest.ts with a static image `import`
// per post plus an exported, date-sorted array. To publish a post: create a new
// folder here with a JSON file and a cover image, then re-run dev/build. No
// component code changes needed.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const IMAGE_EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

const rootDir = path.dirname(fileURLToPath(import.meta.url));
const blogsDir = path.join(rootDir, "..", "src", "content", "blogs");

function toIdentifier(name, index) {
  const base = name.replace(/[^a-zA-Z0-9]+/g, "_").replace(/^[0-9]/, "_$&");
  return `post_${index}_${base}`;
}

let postFolders = [];
try {
  postFolders = readdirSync(blogsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
} catch {
  console.warn(`[generate-blog-manifest] Skipping missing folder: ${blogsDir}`);
}

const posts = [];

for (const folder of postFolders) {
  const folderPath = path.join(blogsDir, folder);
  const files = readdirSync(folderPath, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name);

  const jsonFile = files.find((f) => f.toLowerCase().endsWith(".json"));
  const imageFile = files.find((f) => IMAGE_EXTENSIONS.has(path.extname(f).toLowerCase()));

  if (!jsonFile || !imageFile) {
    console.warn(`[generate-blog-manifest] Skipping "${folder}" — needs one .json file and one image file.`);
    continue;
  }

  let data;
  try {
    data = JSON.parse(readFileSync(path.join(folderPath, jsonFile), "utf8"));
  } catch (err) {
    console.warn(`[generate-blog-manifest] Skipping "${folder}" — invalid JSON: ${err.message}`);
    continue;
  }

  posts.push({ folder, imageFile, data });
}

posts.sort((a, b) => {
  const dateDiff = new Date(b.data.date ?? 0).getTime() - new Date(a.data.date ?? 0).getTime();
  return dateDiff !== 0 ? dateDiff : a.folder.localeCompare(b.folder);
});

const imports = posts
  .map((post, i) => `import ${toIdentifier(post.folder, i)}_image from "./${post.folder}/${post.imageFile}";`)
  .join("\n");

const arrayEntries = posts
  .map((post, i) => {
    const id = toIdentifier(post.folder, i);
    const { title, excerpt, date, author, readTime, tags, content, imageAlt } = post.data;
    return `  {
    slug: ${JSON.stringify(post.folder)},
    image: ${id}_image,
    imageAlt: ${JSON.stringify(imageAlt ?? title ?? "")},
    title: ${JSON.stringify(title ?? "")},
    excerpt: ${JSON.stringify(excerpt ?? "")},
    date: ${JSON.stringify(date ?? "")},
    author: ${JSON.stringify(author ?? "")},
    readTime: ${JSON.stringify(readTime ?? "")},
    tags: ${JSON.stringify(tags ?? [])},
    content: ${JSON.stringify(content ?? [])},
  },`;
  })
  .join("\n");

const manifestSource = `// AUTO-GENERATED by scripts/generate-blog-manifest.mjs — do not edit by hand.
// Regenerated automatically on \`next dev\` / \`next build\`. To publish a post,
// add a folder under src/content/blogs/ containing one .json file and one
// image file, then re-run dev/build.
import type { StaticImageData } from "next/image";

export interface BlogPost {
  slug: string;
  image: StaticImageData;
  imageAlt: string;
  title: string;
  excerpt: string;
  date: string;
  author: string;
  readTime: string;
  tags: string[];
  content: string[];
}

${imports}

export const posts: BlogPost[] = [
${arrayEntries}
];
`;

writeFileSync(path.join(blogsDir, "manifest.ts"), manifestSource, "utf8");
console.log(`[generate-blog-manifest] Wrote ${posts.length} post(s) -> ${path.join(blogsDir, "manifest.ts")}`);
